
# Creating a list
fruits = ["Apple", "Banana", "Mango", "Orange"]

print("Original List:", fruits)

# Accessing elements
print("First element:", fruits[0])
print("Second element:", fruits[1])

# Adding elements
fruits.append("Grapes")
print("After adding Grapes:", fruits)

# Updating elements
fruits[1] = "Watermelon"
print("After updating Banana:", fruits)

# Removing elements
fruits.remove("Orange")
print("After removing Orange:", fruits)

# Sorting the list
fruits.sort()
print("Sorted List:", fruits)

#remove last element
fruits.pop()
print("after poping",fruits)

